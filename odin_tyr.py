class ArbitrationOutcome(str, Enum):
    """Possible arbitration rulings on candidate risks and events."""
    FINDING_SUPPORTED = "FINDING_SUPPORTED"
    FINDING_REJECTED = "FINDING_REJECTED"
    FINDING_REVISED = "FINDING_REVISED"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"
    HUMAN_REVIEW_REQUIRED = "HUMAN_REVIEW_REQUIRED"


class ActionType(str, Enum):
    """Categories of proposed actions that Tyr can draft."""
    RENEWAL_NOTICE = "RENEWAL_NOTICE"
    TERMINATION_NOTICE = "TERMINATION_NOTICE"
    BREACH_NOTICE = "BREACH_NOTICE"
    AMENDMENT_PROPOSAL = "AMENDMENT_PROPOSAL"
    ESCALATION_MEMORANDUM = "ESCALATION_MEMORANDUM"
    INTERNAL_RISK_SUMMARY = "INTERNAL_RISK_SUMMARY"


class ApprovalStatus(str, Enum):
    """Approval lifecycle for drafted legal actions."""
    PENDING_APPROVAL = "PENDING_APPROVAL"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    REQUIRES_MODIFICATION = "REQUIRES_MODIFICATION"


class Evidence(BaseModel):
    """Citation linking a finding or action to exact source text."""
    document_id: str
    clause_id: Optional[str] = None
    source_text: str
    page_number: int = 1
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)


class LokiFindingInput(BaseModel):
    """Candidate risk finding submitted by Loki (Adversarial Review Agent)."""
    risk_id: str
    category: str
