def draft_breach_notice(
    decision: ArbitrationDecision,
    event: Optional[HeimdallEventInput],
    deterministic: DeterministicContext,
) -> ProposedAction:
    """Draft a formal notice of contractual breach or SLA service failure."""
    contracts = list({ev.document_id for ev in decision.supporting_evidence})
    clauses = [f"{ev.document_id} {ev.clause_id}" for ev in decision.supporting_evidence if ev.clause_id]
    
    cure_deadline = deterministic.deadlines.get("cure_deadline", "Within thirty (30) calendar days of receipt")
    
    evidence_quotes = "\n".join([f'  - [{ev.document_id} {ev.clause_id}]: "{ev.source_text.strip()}"' for ev in decision.supporting_evidence[:3]])

    body = f"""================================================================================
FORMAL NOTICE OF CONTRACTUAL BREACH / SLA DEFAULT
================================================================================
DATE: {deterministic.simulated_date}
FROM: {COMPANY_NAME}
NOTICE ADDRESS:
{OFFICIAL_NOTICE_ADDRESS}

TO: Contracting Party / Upstream Provider
AFFECTED AGREEMENTS: {', '.join(contracts)}
RELEVANT PROVISIONS: {', '.join(clauses)}

1. STATEMENT OF BREACH
This letter serves as formal written notice pursuant to the above-referenced
agreements that a material service failure / contractual default has occurred:
{decision.rationale}

2. SUPPORTING CONTRACT EVIDENCE
The contractual commitments breached include:
{evidence_quotes}

3. REQUIRED CURE & REMEDIES
Quillhub Inc. hereby demands that the breach be fully remedied and service
restored to contractual standards {cure_deadline}.
Quillhub reserves all contractual and legal remedies, including rights to service
credits, damages offset, and termination for default.

AUTHORIZED SIGNATORY DRAFT APPROVAL:
[ ] APPROVED by: _______________________ Date: _________
(CEO Priya Chandrasekaran or VP Legal Marcus Ellison required)
================================================================================
"""

    return ProposedAction(
        action_id=f"ACT-BREACH-{decision.item_id}",
        action_type=ActionType.BREACH_NOTICE,
        title=f"Breach Notice regarding {', '.join(contracts)} default",
        intended_recipient="Counterparty Legal Department / Notice Address",
        relevant_contracts=contracts,
        relevant_clauses=clauses,
        supporting_facts=[decision.rationale],
        assumptions=["Counterparty has not provided an unrecorded waiver"],
        proposed_action_body=body,
        applicable_deadline=cure_deadline,
        confidence=decision.confidence,
        approval_status=ApprovalStatus.PENDING_APPROVAL,
        requires_human_approval=True,
        unresolved_issues=[],
    )


