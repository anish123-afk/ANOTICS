class TyrAgentState(BaseModel):
    """Shared state for the Tyr Arbitration & Action Agent."""
    loki_findings: List[LokiFindingInput] = Field(default_factory=list)
    heimdall_events: List[HeimdallEventInput] = Field(default_factory=list)
    deterministic_context: DeterministicContext = Field(default_factory=DeterministicContext)
    
    # Outputs populated by Tyr
    arbitration_decisions: List[ArbitrationDecision] = Field(default_factory=list)
    proposed_actions: List[ProposedAction] = Field(default_factory=list)
    unresolved_questions: List[str] = Field(default_factory=list)


def node_arbitrate_all(state: TyrAgentState) -> Dict[str, Any]:
    """Node 1: Impartially arbitrate every Loki finding and Heimdall event."""
    decisions: List[ArbitrationDecision] = []
    unresolved: List[str] = []

    # Arbitrate Loki findings
    for finding in state.loki_findings:
        decision = arbitrate_loki_finding(finding, state.deterministic_context)
        decisions.append(decision)
        if decision.outcome in [ArbitrationOutcome.INSUFFICIENT_EVIDENCE, ArbitrationOutcome.HUMAN_REVIEW_REQUIRED]:
            unresolved.append(f"Finding {finding.risk_id}: {decision.rationale}")

    # Arbitrate Heimdall events
    for event in state.heimdall_events:
        decision = arbitrate_heimdall_event(event, state.deterministic_context)
        decisions.append(decision)
        if decision.outcome == ArbitrationOutcome.INSUFFICIENT_EVIDENCE:
            unresolved.append(f"Event {event.event_id}: {decision.rationale}")

    return {
        "arbitration_decisions": decisions,
        "unresolved_questions": unresolved,
    }


def node_generate_actions(state: TyrAgentState) -> Dict[str, Any]:
    """Node 2: Generate grounded proposed actions for validated findings and events."""
    actions: List[ProposedAction] = []
    det = state.deterministic_context
    loki_map = {f.risk_id: f for f in state.loki_findings}
    heimdall_map = {e.event_id: e for e in state.heimdall_events}

    for decision in state.arbitration_decisions:
        # Ignore rejected findings or those with insufficient evidence for drafting
        if decision.outcome in [ArbitrationOutcome.FINDING_REJECTED, ArbitrationOutcome.INSUFFICIENT_EVIDENCE]:
            continue

        # Critical findings or human review triggers an executive escalation memo
        if decision.outcome == ArbitrationOutcome.HUMAN_REVIEW_REQUIRED or det.unrecoverable_gap_usd > 10000:
            actions.append(draft_escalation_memorandum(decision, det))

        # Handle Heimdall events
        if decision.item_type == "heimdall_event":
            ev = heimdall_map.get(decision.item_id)
            if ev and "service_level" in ev.potential_trigger.lower() or "downtime" in ev.potential_trigger.lower():
                actions.append(draft_breach_notice(decision, ev, det))

        # Handle Loki findings
        elif decision.item_type == "loki_finding":
            finding = loki_map.get(decision.item_id)
            if finding:
                if finding.category == "financial_recovery_gap":
                    actions.append(draft_amendment_proposal(decision, finding, det))
                elif "renewal" in finding.category.lower():
                    actions.append(draft_renewal_or_termination_notice(decision, det, is_termination=False))
                elif "termination" in finding.category.lower() or "breach" in finding.category.lower():
                    actions.append(draft_renewal_or_termination_notice(decision, det, is_termination=True))

    return {"proposed_actions": actions}


def node_apply_approval_controls(state: TyrAgentState) -> Dict[str, Any]:
    """
    Node 3: Enforce strict safety boundary.
    Ensure every action has PENDING_APPROVAL status and human authorization constraints.
    """
    verified_actions: List[ProposedAction] = []
    for action in state.proposed_actions:
        # Strict enforcement: drafting is not execution
        action.requires_human_approval = True
        action.approval_status = ApprovalStatus.PENDING_APPROVAL
        verified_actions.append(action)

    return {"proposed_actions": verified_actions}


def build_tyr_graph() -> Any:
    """Build the compiled LangGraph workflow for Tyr."""
    workflow = StateGraph(TyrAgentState)

    workflow.add_node("arbitrate", node_arbitrate_all)
    workflow.add_node("generate_actions", node_generate_actions)
    workflow.add_node("approval_controls", node_apply_approval_controls)

    workflow.add_edge(START, "arbitrate")
    workflow.add_edge("arbitrate", "generate_actions")
    workflow.add_edge("generate_actions", "approval_controls")
    workflow.add_edge("approval_controls", END)

    return workflow.compile()


