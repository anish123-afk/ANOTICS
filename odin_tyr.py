def run_tyr(
    loki_findings: Optional[List[LokiFindingInput]] = None,
    heimdall_events: Optional[List[HeimdallEventInput]] = None,
    deterministic_context: Optional[DeterministicContext] = None,
) -> TyrAgentState:
    """
    Execute Phase 9: Tyr Arbitration & Action Agent.

    Args:
        loki_findings: Risk findings submitted by Loki.
        heimdall_events: Triggered events submitted by Heimdall.
        deterministic_context: Calculated dates, exposures, and amendment chains from Phase 5.

    Returns:
        TyrAgentState containing arbitration decisions, drafted actions, and unresolved questions.
    """
    initial_state = TyrAgentState(
        loki_findings=loki_findings or [],
        heimdall_events=heimdall_events or [],
        deterministic_context=deterministic_context or DeterministicContext(),
    )
    graph = build_tyr_graph()
    final_output = graph.invoke(initial_state)
    return TyrAgentState(**final_output)


