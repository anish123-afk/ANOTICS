def arbitrate_loki_finding(
    finding: LokiFindingInput,
    deterministic: DeterministicContext,
) -> ArbitrationDecision:
    """
    Arbitrate a risk finding from Loki:
    - Check if cited evidence is present and valid.
    - Check if the clause has been superseded by an amendment.
    - Check whether the risk is confirmed or speculative.
    """
    conflicts: List[str] = []
    
    # 1. Evidence Check
    if not finding.supporting_evidence:
        return ArbitrationDecision(
            decision_id=f"DEC-{finding.risk_id}",
            item_id=finding.risk_id,
            item_type="loki_finding",
            outcome=ArbitrationOutcome.INSUFFICIENT_EVIDENCE,
            rationale=f"Risk '{finding.risk_id}' rejected because no supporting contractual evidence was provided.",
            supporting_evidence=[],
            confidence=0.2,
        )

    # 2. Amendment Supersession Check
    for ev in finding.supporting_evidence:
        clause_key = f"{ev.document_id}-{ev.clause_id}"
        if clause_key in deterministic.superseded_clauses:
            replacement = deterministic.superseded_clauses[clause_key]
            conflicts.append(f"Clause {clause_key} was superseded by {replacement}.")

    if conflicts:
        revised_desc = f"{finding.description} (NOTE: Applicable terms modified by amendment: {', '.join(conflicts)})"
        return ArbitrationDecision(
            decision_id=f"DEC-{finding.risk_id}",
            item_id=finding.risk_id,
            item_type="loki_finding",
            outcome=ArbitrationOutcome.FINDING_REVISED,
            rationale=f"Risk was revised due to amendment supersession: {'; '.join(conflicts)}",
            supporting_evidence=finding.supporting_evidence,
            revised_finding={"description": revised_desc, "category": finding.category},
            conflicts_detected=conflicts,
            confidence=0.85,
        )

    # 3. High Severity / Ambiguity Escalation
    if finding.severity.lower() == "critical" or finding.unresolved_questions:
        return ArbitrationDecision(
            decision_id=f"DEC-{finding.risk_id}",
            item_id=finding.risk_id,
            item_type="loki_finding",
            outcome=ArbitrationOutcome.HUMAN_REVIEW_REQUIRED,
            rationale=(
                f"Critical severity or unresolved legal ambiguities detected in risk '{finding.risk_id}'. "
                f"Requires human legal counsel review. Unresolved questions: {finding.unresolved_questions}"
            ),
            supporting_evidence=finding.supporting_evidence,
            conflicts_detected=conflicts,
            confidence=0.9,
        )

    # 4. Standard Finding Supported
    return ArbitrationDecision(
        decision_id=f"DEC-{finding.risk_id}",
        item_id=finding.risk_id,
        item_type="loki_finding",
        outcome=ArbitrationOutcome.FINDING_SUPPORTED,
        rationale=f"Risk finding '{finding.risk_id}' is corroborated by valid contract evidence and deterministic rules.",
        supporting_evidence=finding.supporting_evidence,
        conflicts_detected=[],
        confidence=0.95,
    )


def arbitrate_heimdall_event(
    event: HeimdallEventInput,
    deterministic: DeterministicContext,
) -> ArbitrationDecision:
    """
    Arbitrate an operational event alert from Heimdall:
    - Verify that contract clauses connect the event to a genuine legal consequence.
    - Check if event severity justifies action or is mere operational noise.
    """
    if not event.affected_contract_ids:
        return ArbitrationDecision(
            decision_id=f"DEC-{event.event_id}",
            item_id=event.event_id,
            item_type="heimdall_event",
            outcome=ArbitrationOutcome.FINDING_REJECTED,
            rationale=f"Event '{event.event_id}' does not link to any affected contract.",
            supporting_evidence=[],
            confidence=0.1,
        )

    if not event.supporting_evidence:
        return ArbitrationDecision(
            decision_id=f"DEC-{event.event_id}",
            item_id=event.event_id,
            item_type="heimdall_event",
            outcome=ArbitrationOutcome.INSUFFICIENT_EVIDENCE,
            rationale=f"Event '{event.event_id}' lacks contractual clause citations to prove a breach or milestone trigger.",
            supporting_evidence=[],
            confidence=0.3,
        )

    if event.severity.lower() in ["high", "critical"]:
        return ArbitrationDecision(
            decision_id=f"DEC-{event.event_id}",
            item_id=event.event_id,
            item_type="heimdall_event",
            outcome=ArbitrationOutcome.FINDING_SUPPORTED,
            rationale=(
                f"Event '{event.event_id}' ({event.potential_trigger}) on contracts "
                f"{event.affected_contract_ids} is supported by evidence and exceeds alert threshold."
            ),
            supporting_evidence=event.supporting_evidence,
            confidence=0.95,
        )

    return ArbitrationDecision(
        decision_id=f"DEC-{event.event_id}",
        item_id=event.event_id,
        item_type="heimdall_event",
        outcome=ArbitrationOutcome.FINDING_SUPPORTED,
        rationale=f"Routine event '{event.event_id}' logged and confirmed against contract provisions.",
        supporting_evidence=event.supporting_evidence,
        confidence=0.85,
    )


