"""
OdinState — Common Shared State for the Contract Intelligence Project
=====================================================================
State Fields:
- query: str
- retrieved_document: Optional[Dict[str, Any]]
- reExtract: bool = False (by default)
- first_document_name: Optional[str] = Name of the first document in the document series (e.g. A1 for A3, B1 for B2)
"""

import re
from typing import Optional, Dict, Any, List
from pydantic import BaseModel, Field


class OdinState(BaseModel):
    """
    Common state shared across all agents in the project (Thor, Loki, Atreus, etc.).
    """
    query: str = Field(
        default="",
        description="The active natural language query or clause request"
    )
    retrieved_document: Optional[Dict[str, Any]] = Field(
        default=None,
        description="The most recent chunk/document retrieved by Thor (with clause_id, document_name, contract_id, page_number, chunk_id, and clause content/text)"
    )
    retrieved_clause_content: Optional[str] = Field(
        default=None,
        description="The actual full text content of the retrieved clause/section extracted by Thor"
    )
    reExtract: bool = Field(
        default=False,
        description="Flag indicating whether Thor must re-extract (set by Loki when related/subsequent document is found)"
    )
    first_document_name: Optional[str] = Field(
        default=None,
        description="Name of the first document in the document name series (e.g., if document is A3, first_document_name is A1; if B2, first_document_name is B1)"
    )
    financial_review: Optional[Any] = Field(
        default=None,
        description="Financial and deadline compliance reviews generated by agent Norns"
    )
    loki_interpretation: Optional[str] = Field(
        default=None,
        description="Contract interpretation and analysis generated by agent Loki using Claude Haiku"
    )
    heimdall_review: Optional[str] = Field(
        default=None,
        description="Operational incident and event analysis generated by agent Heimdall using Claude Haiku"
    )
    matched_event: Optional[Dict[str, Any]] = Field(
        default=None,
        description="The top operational incident event JSON with highest similarity matched by Heimdall"
    )
    final_judgment: Optional[str] = Field(
        default=None,
        description="The final legal and operational judgment synthesized by Agent Tyr balancing loki_interpretation and heimdall_review"
    )
    final_ans: Optional[str] = Field(
        default=None,
        description="The definitive final answer generated by Agent Tyr after analyzing the final judgment"
    )
    human_approval: Optional[bool] = Field(
        default=None,
        description="Human reviewer approval status for Tyr's final answer (True/False/None)"
    )
    human_feedback: Optional[str] = Field(
        default=None,
        description="Optional feedback or guidance provided by the human during the approval step"
    )

    @staticmethod
    def compute_first_document_name(doc_name: Optional[str]) -> Optional[str]:
        """
        Computes the first document name in a sequential document series.
        Examples:
          'A3' -> 'A1'
          'A2' -> 'A1'
          'A1' -> 'A1'
          'B2' -> 'B1'
          'C1' -> 'C1'
          'STD' -> 'STD'
        """
        if not doc_name:
            return None
        clean = doc_name.strip().upper()
        match = re.match(r"^([A-Z]+)(\d+)$", clean)
        if match:
            prefix = match.group(1)
            return f"{prefix}1"
        return clean

    def update_retrieval(self, query: str, document: Dict[str, Any]):
        """Helper to update query, retrieved document, and compute first_document_name."""
        self.query = query
        self.retrieved_document = document
        self.retrieved_clause_content = (
            document.get("content") or 
            document.get("clause_text") or 
            document.get("clause_content") or 
            document.get("snippet") or 
            ""
        )

        doc_name = document.get("document_name")
        if self.first_document_name is None:
            self.first_document_name = self.compute_first_document_name(doc_name)

    def set_re_extract(self, status: bool):
        """Helper to update reExtract flag."""
        self.reExtract = status

    def update_financial_review(self, review: Any):
        """Helper to update financial_review generated by Norns."""
        self.financial_review = review

    def update_loki_interpretation(self, interpretation: str):
        """Helper to update loki_interpretation generated by Loki."""
        self.loki_interpretation = interpretation

    def update_heimdall_review(self, review: str):
        """Helper to update heimdall_review generated by Heimdall."""
        self.heimdall_review = review

    def update_matched_event(self, event: Dict[str, Any]):
        """Helper to update matched_event generated by Heimdall."""
        self.matched_event = event

    def update_final_judgment(self, judgment: str):
        """Helper to update final_judgment synthesized by Tyr."""
        self.final_judgment = judgment

    def update_final_ans(self, ans: str):
        """Helper to update final_ans generated by Tyr."""
        self.final_ans = ans

    def update_human_approval(self, approved: bool, feedback: Optional[str] = None):
        """Helper to record human approval status and optional feedback."""
        self.human_approval = approved
        self.human_feedback = feedback

    def to_dict(self) -> Dict[str, Any]:
        """Convert state to plain dictionary."""
        return self.model_dump()

    def __repr__(self) -> str:
        doc_id = self.retrieved_document.get("document_name") if self.retrieved_document else "None"
        clause = self.retrieved_document.get("clause_id") if self.retrieved_document else "None"
        has_loki = bool(self.loki_interpretation)
        has_review = bool(self.financial_review)
        has_heimdall = bool(self.heimdall_review)
        has_judgment = bool(self.final_judgment)
        has_ans = bool(self.final_ans)
        approved = self.human_approval
        return (
            f"<OdinState query='{self.query}' first_doc='{self.first_document_name}' "
            f"current_doc={doc_id}:{clause} reExtract={self.reExtract} "
            f"has_loki={has_loki} has_review={has_review} has_heimdall={has_heimdall} "
            f"has_judgment={has_judgment} has_ans={has_ans} approved={approved}>"
        )
